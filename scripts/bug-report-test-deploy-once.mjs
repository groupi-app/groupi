export function checkedKey(env) {
  if (
    env.VERCEL_ENV !== 'preview' ||
    env.VERCEL_TARGET_ENV === 'production' ||
    env.VERCEL_GIT_COMMIT_REF !== branch
  ) {
    throw new Error('Runner requires the exact non-production preview branch.');
  }
  const key = env.BUG_REPORT_TEST_DEPLOY_KEY;
  if (
    typeof key !== 'string' ||
    !/^(dev|preview):zany-rooster-824\|[^\s]+$/.test(key)
  ) {
    throw new Error('Runner requires a deployment-scoped TEST key.');
  }
  return key;
}

export function verifySources() {
  const actualPaths = [];
  function walk(directory) {
    for (const entry of readdirSync(resolve(root, directory), {
      withFileTypes: true,
    })) {
      if (entry.name === 'node_modules' || entry.name === '.git') continue;
      const path = `${directory}/${entry.name}`;
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile()) actualPaths.push(path);
      else throw new Error(`Unsupported backend source entry: ${path}`);
    }
  }
  for (const directory of ['convex', 'packages/shared', 'patches'])
    walk(directory);
  for (const path of actualPaths) {
    if (!Object.hasOwn(manifest, path))
      throw new Error(`Unreviewed backend source added: ${path}`);
  }
  for (const [path, expected] of Object.entries(manifest)) {
    const actual = createHash('sha256')
      .update(readFileSync(resolve(root, path)))
      .digest('hex');
    if (actual !== expected)
      throw new Error(`Reviewed backend source differs: ${path}`);
  }
}

// Keep failure diagnostics bounded and redact credentials before emitting them.
export function safeDiagnostics(output, secretValues = []) {
  let text = String(output ?? '').replace(/\x1b\[[0-?]*[ -/]*[@-~]/g, '');
  for (const value of secretValues.filter(
    value => typeof value === 'string' && value.length >= 6
  )) {
    for (const encoded of [
      value,
      encodeURIComponent(value),
      Buffer.from(value).toString('base64'),
    ]) {
      text = text.split(encoded).join('[REDACTED]');
    }
  }
  text = text
    .replace(/"[^"\n]*"|'[^'\n]*'|`[^`\n]*`/g, '[QUOTED]')
    .replace(/(?:https?|wss?):\/\/[^\s<>"']+/gi, '[URL]')
    .replace(/\b(?:dev|prod|preview):[^\s|]+\|[^\s]+/gi, '[DEPLOY_KEY]')
    .replace(/\bBearer\s+\S+/gi, 'Bearer [TOKEN]')
    .replace(
      /\b[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b/g,
      '[JWT]'
    )
    .replace(/\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/gi, '[EMAIL]')
    .replace(
      /((?:key|token|secret|password|authorization|cookie|dsn)\s*[:=]\s*)[^\s,;]+/gi,
      '$1[REDACTED]'
    )
    .replace(/[A-Za-z0-9_+\/=-]{24,}/g, '[OPAQUE]')
    .replace(/[\x00-\x08\x0b-\x1f\x7f]/g, '');
  const lines = text
    .slice(-100000)
    .split(/\r?\n/)
    .filter(line =>
      /error|fail|cannot|could not|typecheck|bundl|deploy|TS\d{4}/i.test(line)
    )
    .slice(-12)
    .map(line => line.trim().slice(0, 240));
  return (
    lines.join('\n').slice(0, 2500) || 'No safe diagnostic lines available.'
  );
}

export function run() {
  const key = checkedKey(process.env);
  for (const entry of readdirSync(root)) {
    if (entry === '.env' || entry === '.env.local') {
      throw new Error(
        'Environment files are prohibited in the isolated runner.'
      );
    }
  }
  verifySources();
  console.log('Runner target and reviewed-source checks passed.');
  const require = createRequire(import.meta.url);
  const sharp = require('sharp');
  if (sharp.versions?.sharp !== '0.35.5' || !sharp.versions?.vips) {
    throw new Error('Expected prebuilt Sharp runtime is unavailable.');
  }
  console.log(
    'Prebuilt image runtime check passed; starting typechecked TEST deployment.'
  );
  const temporary = mkdtempSync(resolve(tmpdir(), 'groupi-test-deploy-'));
  try {
    // Allowlist, not a denylist: no inherited Convex targets, Sentry credentials,
    // Vercel indicators, application secrets, or credential-store configuration.
    const env = {
      PATH: process.env.PATH ?? '',
      HOME: temporary,
      TMPDIR: temporary,
      CI: '1',
      CONVEX_DEPLOY_KEY: key,
      NODE_OPTIONS: '--max-old-space-size=3072',
    };
    const result = spawnSync(
      process.execPath,
      [
        resolve(root, 'node_modules/convex/bin/main.js'),
        'deploy',
        '--yes',
        '--typecheck',
        'enable',
        '--codegen',
        'enable',
        '--skip-workos-check',
      ],
      { cwd: root, env, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }
    );
    // Emit bounded redacted diagnostics only; never raw SDK output.
    if (result.error || result.status !== 0) {
      const secrets = [
        key,
        ...Object.entries(process.env)
          .filter(([name]) =>
            /key|token|secret|password|authorization|cookie|dsn/i.test(name)
          )
          .map(([, value]) => value),
      ];
      console.error(
        safeDiagnostics(
          `${result.stdout ?? ''}\n${result.stderr ?? ''}`,
          secrets
        )
      );
      throw new Error(
        `TEST backend deployment failed (exit ${result.status ?? 'none'}, signal ${result.signal ?? 'none'}); no status artifact published.`
      );
    }
    const output = resolve(root, 'groupi-bug-report-test-deploy-status');
    rmSync(output, { recursive: true, force: true });
    mkdirSync(output, { recursive: true });
    writeFileSync(
      resolve(output, 'index.html'),
      '<!doctype html><title>TEST backend runner</title><p>TEST backend deployment completed.</p>'
    );
    console.log(
      `TEST backend deployment completed from reviewed source ${reviewedCommit}.`
    );
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    run();
  } catch (error) {
    console.error(
      error instanceof Error ? error.message : 'TEST runner failed.'
    );
    process.exitCode = 1;
  }
}
